//go:build ignore

// Command gen writes the lab test root: internal/labroot/testdata (the root and
// the key seeds) and internal/labroot/denylist.go (the key ids the production
// binaries refuse). Run it from the repository root:
//
//	go run internal/labroot/gen/main.go
//
// The seeds are derived from fixed labels, so the output is the same every time
// and the files are public on purpose: this root signs lab and CI bundles only,
// and its key ids are on the deny list of every binary built without the
// ctrlz_lab tag (p4-nodes 7.1).
package main

import (
	"crypto/ed25519"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"time"

	"google.golang.org/protobuf/encoding/protojson"

	signv1 "github.com/Kup1ng/CtrlZ-Shared/gen/ctrlz/sign/v1"
	"github.com/Kup1ng/CtrlZ-Shared/manifest"
)

func main() {
	names := []string{"root-1", "root-2", "root-3", "policy", "catalog"}
	dir := filepath.Join("internal", "labroot", "testdata")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		panic(err)
	}
	root := &signv1.Root{
		Version: 1,
		// The year 2100: a lab root that expires would fail every lab run at once.
		ExpiresAt: time.Date(2100, 1, 1, 0, 0, 0, 0, time.UTC).Unix(),
		Threshold: 2,
	}
	ids := map[string][]byte{}
	for _, n := range names {
		seed := sha256.Sum256([]byte("ctrlz-lab-root-v1/" + n))
		priv := ed25519.NewKeyFromSeed(seed[:])
		pub := priv.Public().(ed25519.PublicKey)
		id := manifest.KeyID(pub)
		ids[n] = id
		root.Keys = append(root.Keys, &signv1.PublicKey{KeyId: id, Ed25519: pub})
		if err := os.WriteFile(filepath.Join(dir, n+".seed"), []byte(hex.EncodeToString(seed[:])+"\n"), 0o644); err != nil {
			panic(err)
		}
	}
	exp := root.ExpiresAt
	rootIDs := [][]byte{ids["root-1"], ids["root-2"], ids["root-3"]}
	root.RootKeyIds = rootIDs
	root.Roles = []*signv1.RoleGrant{
		{Role: signv1.Role_ROLE_POLICY, KeyIds: [][]byte{ids["policy"]}, Threshold: 1, ExpiresAt: exp},
		{Role: signv1.Role_ROLE_CATALOG, KeyIds: [][]byte{ids["catalog"]}, Threshold: 1, ExpiresAt: exp},
		{Role: signv1.Role_ROLE_BUNDLE, KeyIds: rootIDs, Threshold: 2, ExpiresAt: exp},
	}
	b, err := protojson.MarshalOptions{Multiline: true}.Marshal(root)
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "root.json"), append(b, '\n'), 0o644); err != nil {
		panic(err)
	}
	src := "// Code generated by internal/labroot/gen; DO NOT EDIT.\n\npackage labroot\n\n" +
		"// denyHex are the key ids of the lab test root (testdata/root.json).\n" +
		"func denyHex() []string {\n\treturn []string{\n"
	for _, k := range root.Keys {
		src += fmt.Sprintf("\t\t%q,\n", hex.EncodeToString(k.KeyId))
	}
	src += "\t}\n}\n"
	if err := os.WriteFile(filepath.Join("internal", "labroot", "denylist.go"), []byte(src), 0o644); err != nil {
		panic(err)
	}
}
